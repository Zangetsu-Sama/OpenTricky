"""The RCDATA resources of ssx_recomp.rc as a C table, for POSIX builds.

    rc_embed.py <ssx_recomp.rc> <out.c>

Windows links the .rc into the executable; macOS and Linux have no resource
compiler, so the same entries (NAME RCDATA "file") become byte arrays and the
xr_embedded_resources table that FindResourceA in win32_compat_ext.c reads.
"""
import re
import sys

LINE = re.compile(r'^\s*([A-Za-z_][A-Za-z0-9_]*)\s+RCDATA\s+"([^"]+)"')


def main():
    rc, out = sys.argv[1], sys.argv[2]
    entries = []
    for line in open(rc, encoding="utf-8", errors="replace"):
        m = LINE.match(line)
        if m:
            entries.append((m.group(1), m.group(2)))
    with open(out, "w") as f:
        f.write("/* Generated by port/tools/rc_embed.py from ssx_recomp.rc. */\n")
        f.write("typedef struct { const char *name; const unsigned char *data; unsigned int size; } res_t;\n")
        for i, (name, path) in enumerate(entries):
            data = open(path, "rb").read() + b"\0"   # text resources end with a NUL
            f.write("static const unsigned char r%d[%d] = {" % (i, len(data)))
            for k in range(0, len(data), 32):
                f.write("\n" + ",".join(str(b) for b in data[k:k + 32]) + ",")
            f.write("};\n")
        f.write("const res_t xr_embedded_resources[] = {\n")
        for i, (name, path) in enumerate(entries):
            size = len(open(path, "rb").read())
            f.write('    { "%s", r%d, %d },\n' % (name, i, size))
        if not entries:
            f.write('    { "", 0, 0 },\n')
        f.write("};\n")
        f.write("const unsigned int xr_embedded_resource_count = %d;\n" % len(entries))
    print("rc_embed: %d resources" % len(entries))


if __name__ == "__main__":
    main()
